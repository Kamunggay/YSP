import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import SwaggerParser from '@apidevtools/swagger-parser';
import openapiTS, { astToString } from 'openapi-typescript';

// Give shared definitions stable component names before bundling. Otherwise the
// bundler can target a oneOf member and the generator emits invalid TS indexing.
const source = JSON.parse(await readFile(new URL('./v1/api-v1.json', import.meta.url), 'utf8'));
const shared = JSON.parse(await readFile(new URL('./v1/transport.schema.json', import.meta.url), 'utf8'));
function nameSharedRefs(value, prefix) {
  if (Array.isArray(value)) return value.map(child => nameSharedRefs(child, prefix));
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, child]) => [key,
    key === '$ref' && typeof child === 'string' && child.startsWith(prefix)
      ? child.replace(prefix, '#/components/schemas/') : nameSharedRefs(child, prefix),
  ]));
  return value;
}
const input = nameSharedRefs(source, './transport.schema.json#/$defs/');
Object.assign(input.components.schemas, nameSharedRefs(shared.$defs, '#/$defs/'));
// Resolve local shared definitions first; generation must never fetch remote schemas.
const api = await SwaggerParser.bundle(fileURLToPath(new URL('./v1/api-v1.json', import.meta.url)), input, {
  resolve: { http: false },
});
const types = astToString(await openapiTS(api, { alphabetize: true }));
const methods = ['get', 'post', 'put', 'patch', 'delete', 'head', 'options', 'trace'];
const routes = {};
for (const [path, item] of Object.entries(api.paths)) {
  for (const method of methods.filter(method => item[method])) {
    const operation = item[method];
    assert.ok(operation.operationId && !Object.hasOwn(routes, operation.operationId), 'unique stable operation ID');
    const base = (operation.servers ?? item.servers ?? api.servers)[0].url;
    assert.ok(base.startsWith('/') && !base.startsWith('//'), 'local origin-relative base');
    routes[operation.operationId] = { method: method.toUpperCase(), path: `${base.replace(/\/$/, '')}${path}` };
  }
}
const outputs = {
  'api.d.ts': types,
  'routes.ts': `// Generated by generate.mjs from canonical OpenAPI; do not edit.\nexport const routes = ${JSON.stringify(routes, null, 2)} as const;\n`,
};
const resolved = await SwaggerParser.dereference(structuredClone(api), { resolve: { http: false } });
const consumerSchemas = {};
for (const item of Object.values(resolved.paths)) {
  for (const method of methods.filter(method => item[method])) {
    const op = item[method];
    if (!op['x-session-consumer']) continue;
    consumerSchemas[op.operationId] = { oneOf: Object.entries(op.responses).map(([status, response]) => {
      const properties = { kind: { const: 'response' }, status: { const: Number(status) } };
      if (response.content) properties.body = response.content['application/json'].schema;
      if (status === '429') properties.retryAfter = response.headers['Retry-After'].schema;
      return { type: 'object', additionalProperties: false, required: Object.keys(properties), properties };
    }) };
  }
}
outputs['session-validation.json'] = `${JSON.stringify(consumerSchemas, null, 2)}\n`;
const exchanges = (await Promise.all(['session', 'enrollment', 'mfa-recovery', 'chapter-context', 'membership', 'duty-grant', 'policy'].map(async slice =>
  JSON.parse(await readFile(new URL(`./v1/${slice}-exchanges.json`, import.meta.url), 'utf8'))))).flat();
const examples = exchanges.map(({ operationId, request, response }) => ({
  operationId,
  request: {
    ...(Object.hasOwn(request, 'body') ? { body: request.body } : {}),
    ...(request.query ? { query: request.query } : {}),
    ...(request.path ? { path: request.path } : {}),
    ...(request.header?.['X-Chapter-Context'] ? { contextRevision: request.header['X-Chapter-Context'] } : {}),
  },
  response: { kind: 'response', status: response.status,
    ...(Object.hasOwn(response, 'body') ? { body: response.body } : {}),
    ...(response.status === 429 ? { retryAfter: response.headers['retry-after'] } : {}),
  },
}));
// Malformed request fixtures validate as rejections, not as valid typed requests.
const invalidRequest = index => {
  const operation = api.paths[exchanges[index].path][exchanges[index].method];
  return [...(operation['x-invalid-request-statuses'] ?? []), ...(operation['x-invalid-parameter-statuses'] ?? [])]
    .includes(exchanges[index].response.status);
};
const validExamples = examples.filter((_, index) => !invalidRequest(index));
const invalidExamples = examples.filter((_, index) => invalidRequest(index))
  .map(({ operationId, response }) => ({ operationId, response }));
outputs['session-examples.ts'] = '// Generated from the validated operation exchanges; do not edit.\n'
  + 'import type { ConsumerExample, ConsumerResponseExample } from "../consumer/session.ts";\n'
  + `export const consumerExamples = ${JSON.stringify(validExamples, null, 2)} as const satisfies readonly ConsumerExample[];\n`
  + `export const rejectedRequestResponses = ${JSON.stringify(invalidExamples, null, 2)} as const satisfies readonly ConsumerResponseExample[];\n`;
await mkdir(new URL('./generated/', import.meta.url), { recursive: true });
for (const [name, output] of Object.entries(outputs)) {
  const target = new URL(`./generated/${name}`, import.meta.url);
  if (process.argv.includes('--check')) assert.equal((await readFile(target, 'utf8')).replaceAll('\r\n', '\n'), output, `generation drift: ${name}; run npm run generate`);
  else await writeFile(target, output);
}
